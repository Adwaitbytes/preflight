"""Generate schema/*.json and web/src/lib/types.ts from core/models.py.

`uv run python scripts/gen_contract.py` writes both; `--check` exits 1 if either is stale,
which CI runs so the Python and TypeScript contracts can never drift.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from pydantic import BaseModel

from preflight.core import models

ROOT = Path(__file__).resolve().parent.parent
SCHEMA_DIR = ROOT / "schema"
TYPES_TS = ROOT / "web" / "src" / "lib" / "types.ts"

EXPORTED: list[type[BaseModel]] = [
    models.DoctorReport,
    models.NeuronHistory,
    models.FleetReport,
    models.LiveFeed,
    models.MinerEconomics,
    models.TxReport,
    models.SimRequest,
    models.SimResult,
    models.ErrorExplanation,
    models.LaunchPlan,
    models.SubnetCard,
    models.HealthScores,
    models.SubnetDetail,
    models.AskAnswer,
    models.ServiceHealth,
]


def _ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(_ts_type(s) for s in schema["anyOf"]))
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    kind = schema.get("type")
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(_ts_type(s) for s in schema["prefixItems"]) + "]"
        return f"Array<{_ts_type(schema.get('items', {}))}>"
    if kind == "object":
        extra = schema.get("additionalProperties")
        value = _ts_type(extra) if isinstance(extra, dict) else "unknown"
        return f"Record<string, {value}>"
    return "unknown"


def _interface(name: str, schema: dict[str, Any]) -> str:
    if "enum" in schema:
        return f"export type {name} = {_ts_type(schema)};\n"
    required = set(schema.get("required", []))
    lines = [f"export interface {name} {{"]
    for prop, spec in schema.get("properties", {}).items():
        doc = spec.get("description")
        if doc:
            lines.append(f"  /** {doc} */")
        optional = "" if prop in required else "?"
        lines.append(f"  {prop}{optional}: {_ts_type(spec)};")
    lines.append("}\n")
    return "\n".join(lines)


def render() -> tuple[dict[str, str], str]:
    schemas: dict[str, str] = {}
    definitions: dict[str, dict[str, Any]] = {}
    for model in EXPORTED:
        schema = model.model_json_schema(mode="serialization")
        schemas[f"{model.__name__}.json"] = json.dumps(schema, indent=2, sort_keys=True) + "\n"
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema
    header = (
        "// GENERATED by scripts/gen_contract.py from src/preflight/core/models.py. Do not edit.\n"
        "// Run `uv run python scripts/gen_contract.py` after changing the models.\n\n"
    )
    body = "\n".join(_interface(name, definitions[name]) for name in sorted(definitions))
    return schemas, header + body


def main() -> int:
    check = "--check" in sys.argv
    schemas, types_ts = render()
    stale: list[str] = []
    for name, text in schemas.items():
        path = SCHEMA_DIR / name
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if check:
        if not TYPES_TS.exists() or TYPES_TS.read_text() != types_ts:
            stale.append(str(TYPES_TS.relative_to(ROOT)))
        if stale:
            print("Contract is stale, run scripts/gen_contract.py:\n  " + "\n  ".join(stale))
            return 1
        print("Contract is current")
        return 0
    TYPES_TS.parent.mkdir(parents=True, exist_ok=True)
    TYPES_TS.write_text(types_ts)
    print(f"Wrote {len(schemas)} schemas and {TYPES_TS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
